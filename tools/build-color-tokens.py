def lum(s):
 c=[int(s[i:i+2],16)/255 for i in (1,3,5)];c=[x/12.92 if x<=.04045 else ((x+.055)/1.055)**2.4 for x in c]
 return .2126*c[0]+.7152*c[1]+.0722*c[2]
def ratio(a,b):
 a,b=sorted([lum(a),lum(b)]);return (b+.05)/(a+.05)
def build():
 data={'name':'I SAW','version':'1.2.0','colorSpace':'oklch','steps':STEPS,'palettes':{},'aliases':ALIASES,'semantic':SEMANTIC}
 css=['/* Generated by tools/build-color-tokens.py. Edit the OKLCH source there. */',':root {']
 for family,meta in PALETTES.items():
  shades={};previous=2
  for step,(L,C,h) in zip(STEPS,meta['values']):
   assert L<previous,(family,step,'lightness must decrease');previous=L
   # Authored colors stay inside sRGB; do not rely on browser clipping.
   rgb=linear(L,C,h);assert all(-.000001<=x<=1.000001 for x in rgb),(family,step,'outside sRGB',rgb)
   if family=='neutral':assert C==0
   value=f'oklch({L*100:.6f}% {C:.8f} {h:.6f})'
   shades[str(step)]={'oklch':value,'hex':srgbhex(L,C,h),'l':round(L,9),'c':round(C,9),'h':round(h,6)}
   css.append(f'  --{family}-{step}: {value};')
