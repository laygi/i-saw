import math

def to_oklch(s):
 rgb=[int(s[i:i+2],16)/255 for i in (1,3,5)]
 r,g,b=[x/12.92 if x<=.04045 else ((x+.055)/1.055)**2.4 for x in rgb]
 l=(.4122214708*r+.5363325363*g+.0514459929*b)**(1/3)
 m=(.2119034982*r+.6806995451*g+.1073969566*b)**(1/3)
 s=(.0883024619*r+.2817188376*g+.6299787005*b)**(1/3)
 L=.2104542553*l+.793617785*m-.0040720468*s
 a=1.9779984951*l-2.428592205*m+.4505937099*s
 b=.0259040371*l+.7827717662*m-.808675766*s
 return L,math.hypot(a,b),math.degrees(math.atan2(b,a))%360

def linear(L,C,h):
 a=C*math.cos(math.radians(h));b=C*math.sin(math.radians(h))
 l=(L+.3963377774*a+.2158037573*b)**3
 m=(L-.1055613458*a-.0638541728*b)**3
 s=(L-.0894841775*a-1.291485548*b)**3
 return (4.0767416621*l-3.3077115913*m+.2309699292*s,-1.2684380046*l+2.6097574011*m-.3413193965*s,-.0041960863*l-.7034186147*m+1.707614701*s)

def srgbhex(L,C,h):
 values=linear(L,C,h)
 out=[12.92*x if x<=.0031308 else 1.055*x**(1/2.4)-.055 for x in values]
 return '#'+''.join(f'{max(0,min(255,round(x*255))):02x}' for x in out)


